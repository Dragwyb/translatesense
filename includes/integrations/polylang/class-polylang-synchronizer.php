/**
 * Synchronizes a TranslateSense-created translation with Polylang.
 *
 * This class deliberately keeps Polylang's synchronization internals behind
 * one guarded adapter. It is called by the shared translation pipeline, so
 * backend AI and browser-based providers receive the same synchronization.
 *
 * Important:
 * - Polylang's `$polylang->sync` models are internal APIs, not WordPress APIs.
 * - Every internal access is guarded and failures are reported as warnings.
 * - Filters are registered only for the active source/target pair and are
 *   always removed, including when a synchronization call throws an error.
 * - Translated builder data is written after generic metadata synchronization.
 *
 * @package TranslateSense
 */
class Polylang_Synchronizer {

	/**
	 * Active source/target context used by the scoped Polylang filters.
	 *
	 * @var array
	 */
	private static $context = array();

	/**
	 * Prevent nested Polylang sync operations from replacing the active pair.
	 *
	 * @var bool
	 */
	private static $running = false;

	/**
	 * Translated attachment IDs created/resolved during the current translation.
	 *
	 * @var int[]
	 */
	private static $pending_media_attachments = array();

	/**
	 * Metadata which must not be overwritten by generic source-to-target copy.
	 *
	 * Builder data is generated by the TranslateSense builders and must be
	 * restored after generic Polylang metadata synchronization.
	 *
	 * @return string[]
	 */
	private static function protected_meta_keys(): array {
		$keys = array(
			'_edit_last',
			'_edit_lock',
			'_elementor_data',
			'_elementor_edit_mode',
			'_elementor_page_settings',
			'_elementor_template_type',
			'_elementor_css',
			'_elementor_controls_usage',
		);

		/**
		 * Filters metadata excluded from generic Polylang synchronization.
		 *
		 * @param string[] $keys Metadata keys.
		 */
		$keys = apply_filters( 'translatesense_sync_protected_post_meta', $keys );

		return array_values(
			array_unique(
				array_filter(
					(array) $keys,
					'is_string'
				)
			)
		);
	}

	/**
	 * Get the active Polylang instance.
	 *
	 * Polylang exposes PLL() in supported releases. Avoid relying on a global
	 * variable because the instance can differ between admin/REST contexts.
	 *
	 * @return object|null
	 */
	private static function get_polylang_instance() {
		if ( function_exists( 'PLL' ) ) {
			$polylang = PLL();
			return is_object( $polylang ) ? $polylang : null;
		}

		return null;
	}

	/**
	 * Check whether a Polylang sync model exposes the requested copy method.
	 *
	 * @param object|null $polylang Polylang instance.
	 * @return bool
	 */
	private static function can_copy( $polylang ): bool {
		return is_object( $polylang )
			&& isset( $polylang->sync )
			&& is_object( $polylang->sync )
			&& isset( $polylang->sync->taxonomies )
			&& is_object( $polylang->sync->taxonomies )
			&& is_callable( array( $polylang->sync->taxonomies, 'copy' ) )
			&& isset( $polylang->sync->post_metas )
			&& is_object( $polylang->sync->post_metas )
			&& is_callable( array( $polylang->sync->post_metas, 'copy' ) );
	}

	/**
	 * Copy Polylang-managed taxonomies and metadata from source to target.
	 *
	 * This is intentionally invoked only after the target language and
	 * translation relationship have been saved. The scoped filters below
	 * expand the copy lists only for this exact source/target pair.
	 *
	 * @param int    $source_post_id Source post ID.
	 * @param int    $target_post_id Target post ID.
	 * @param string $target_lang    Target language slug.
	 * @param bool   $is_new         Whether this call created the target post.
	 * @return array {
	 *     @type bool     $success           Whether all available operations succeeded.
	 *     @type bool     $taxonomies_synced Whether taxonomy copy ran.
	 *     @type bool     $post_meta_synced  Whether metadata copy ran.
	 *     @type bool     $media_synced      Whether featured media was translated.
	 *     @type string[] $warnings          Non-fatal warnings.
	 *     @type bool     $skipped           Whether generic synchronization was intentionally skipped.
	 * }
	 */
	public static function synchronize( int $source_post_id, int $target_post_id, string $target_lang, bool $is_new = false ): array {
		$result = array(
			'success'           => true,
			'taxonomies_synced' => false,
			'post_meta_synced'  => false,
			'media_synced'      => false,
			'warnings'          => array(),
			'skipped'           => false,
		);

		if ( self::$running ) {
			$result['success']    = false;
			$result['warnings'][] = __( 'A nested Polylang synchronization was skipped to prevent recursive copy operations.', 'translatesense' );
			return $result;
		}

		$source_post = get_post( $source_post_id );
		$target_post = get_post( $target_post_id );

		if ( ! $source_post instanceof WP_Post || ! $target_post instanceof WP_Post ) {
			$result['success']    = false;
			$result['warnings'][] = __( 'Polylang synchronization skipped because the source or target post no longer exists.', 'translatesense' );
			return $result;
		}

		if ( $source_post->post_type !== $target_post->post_type ) {
			$result['success']    = false;
			$result['warnings'][] = __( 'Polylang synchronization skipped because the source and target post types do not match.', 'translatesense' );
			return $result;
		}

		$actual_target_language = Polylang_Bridge::get_post_language( $target_post_id );
		if ( $actual_target_language && $actual_target_language !== $target_lang ) {
			$result['success']    = false;
			$result['warnings'][] = __( 'Polylang synchronization skipped because the target post language does not match the requested language.', 'translatesense' );
			return $result;
		}

		// Match Polylang's translation-copy semantics: generic taxonomy and
		// metadata duplication is performed for a newly created translation.
		// manually edited taxonomy assignments or builder-specific settings.
		if ( ! $is_new ) {
			// but no generic Polylang copy/sync operation was performed here.
			$result['skipped'] = true;
			return $result;
		}

		$polylang = self::get_polylang_instance();

		if ( ! self::can_copy( $polylang ) ) {
			$result['success']    = false;
			$result['warnings'][] = __( 'Polylang synchronization models are unavailable. The translated post was saved, but taxonomy and metadata synchronization could not run.', 'translatesense' );
			return $result;
		}

		self::$running = true;
		self::$context = array(
			'source_post_id' => $source_post_id,
			'target_post_id' => $target_post_id,
		);

		// Media/term callbacks are scoped to this synchronization operation.
		add_filter( 'pll_copy_taxonomies', array( __CLASS__, 'filter_copy_taxonomies' ), 99, 4 );
		add_filter( 'pll_copy_post_metas', array( __CLASS__, 'filter_copy_post_metas' ), 99, 4 );
		add_filter( 'pll_translate_post_meta', array( __CLASS__, 'translate_post_meta' ), 10, 3 );
		add_filter( 'pll_maybe_translate_term', array( __CLASS__, 'maybe_translate_term' ), 10, 3 );

		try {
			// Copy taxonomies first so term translation relationships are
			// available to integrations which inspect the target post metadata.
			$polylang->sync->taxonomies->copy( $source_post_id, $target_post_id, $target_lang );
			$result['taxonomies_synced'] = true;

			// Copy configured/custom metadata. Protected builder and plugin
			// operational metadata is excluded by filter_copy_post_metas().
			$polylang->sync->post_metas->copy( $source_post_id, $target_post_id, $target_lang );
			$result['post_meta_synced'] = true;

			// Polylang can intentionally disable ordinary post-meta sync. ACF
			// repeater/flexible-content parent values and field-key references
			// are structural data, so preserve those even in that configuration.
			$post_meta_sync_enabled = isset( $polylang->options['sync'] )
				&& is_array( $polylang->options['sync'] )
				&& in_array( 'post_meta', $polylang->options['sync'], true );

			if ( ! $post_meta_sync_enabled ) {
				self::sync_acf_structural_fields( $source_post_id, $target_post_id );
			}

			// Some Polylang versions/integrations may not route the featured
			// image through pll_translate_post_meta. Ensure it is translated
			// once more through the same guarded media resolver.
			$source_thumbnail_id = (int) get_post_thumbnail_id( $source_post_id );
			if ( $source_thumbnail_id > 0 ) {
				$target_thumbnail_id = self::resolve_media_translation( $source_thumbnail_id, $target_lang );
				if ( $target_thumbnail_id > 0 ) {
					set_post_thumbnail( $target_post_id, $target_thumbnail_id );
					$result['media_synced'] = ( $target_thumbnail_id !== $source_thumbnail_id );
				}
			}

			// Notify integrations only after the actual synchronization calls
			// have completed. These are Polylang lifecycle hooks, not a
			// substitute for calling the synchronization models above.
			if ( $is_new ) {
				$translations   = Polylang_Bridge::get_post_translations( $source_post_id );
				$source_wp_post = get_post( $source_post_id );

				/**
				 * Fires after a synchronized translated post has been created.
				 *
				 * @param int    $source_post_id Source post ID.
				 * @param int    $target_post_id Newly created translated post ID.
				 * @param string $target_lang    Target language slug.
				 */
				// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- Polylang integration hook.
				do_action( 'pll_created_sync_post', $source_post_id, $target_post_id, $target_lang );

				if ( $source_wp_post instanceof WP_Post ) {
					/**
					 * Polylang save lifecycle notification after updating the
					 * source post's translation group.
					 *
					 * @param int     $source_post_id Source post ID.
					 * @param WP_Post $source_wp_post Source post object.
					 * @param array   $translations   Translation map.
					 */
					// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- Polylang integration hook.
					do_action( 'pll_save_post', $source_post_id, $source_wp_post, $translations );
				}
			}

			/**
			 * Fires after TranslateSense has completed a Polylang copy/sync pass.
			 *
			 * @param int    $source_post_id Source post ID.
			 * @param int    $target_post_id Target post ID.
			 * @param string $target_lang    Target language slug.
			 * @param string $strategy       Synchronization strategy (`copy`).
			 */
			// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- Polylang integration hook.
			do_action( 'pll_post_synchronized', $source_post_id, $target_post_id, $target_lang, 'copy' );

		} catch ( \Throwable $throwable ) {
			$result['success']    = false;
			$result['warnings'][] = sprintf(
				/* translators: %s: error message */
				__( 'Polylang synchronization encountered an error: %s', 'translatesense' ),
				$throwable->getMessage()
			);
		} finally {
			remove_filter( 'pll_copy_taxonomies', array( __CLASS__, 'filter_copy_taxonomies' ), 99 );
			remove_filter( 'pll_copy_post_metas', array( __CLASS__, 'filter_copy_post_metas' ), 99 );
			remove_filter( 'pll_translate_post_meta', array( __CLASS__, 'translate_post_meta' ), 10 );
			remove_filter( 'pll_maybe_translate_term', array( __CLASS__, 'maybe_translate_term' ), 10 );
			self::$context = array();
			self::$running = false;
		}

		return $result;
	}

	/**
	 * Expand the taxonomy list only for the active source/target pair.
	 *
	 * This mirrors the competitor's pll_copy_taxonomies integration without
	 * keeping a permanent global filter that changes unrelated Polylang copies.
	 *
	 * @param string[] $taxonomies Taxonomy names selected by Polylang.
	 * @param bool     $sync       Whether this is a synchronization operation.
	 * @param int      $from       Source post ID.
	 * @param int      $to         Target post ID.
	 * @return string[]
	 */
	public static function filter_copy_taxonomies( $taxonomies, $sync, $from, $to ): array {
		if ( ! self::is_active_pair( $from, $to ) ) {
			return (array) $taxonomies;
		}

		$internal_taxonomies = get_taxonomies( array( '_pll' => true ), 'names' );
		$source_taxonomies   = get_post_taxonomies( (int) $from, 'names' );

		return array_values( array_diff( $source_taxonomies, (array) $internal_taxonomies ) );
	}

	/**
	 * Expand the metadata list for this pair and protect plugin/builder state.
	 *
	 * Merge source and target keys so Polylang can also remove stale target
	 * values when the source key has been removed, subject to the exclusions.
	 *
	 * @param string[] $keys Metadata keys selected by Polylang.
	 * @param bool     $sync Whether this is a synchronization operation.
	 * @param int      $from Source post ID.
	 * @param int      $to   Target post ID.
	 * @return string[]
	 */
	public static function filter_copy_post_metas( $keys, $sync, $from, $to ): array {
		if ( ! self::is_active_pair( $from, $to ) ) {
			return (array) $keys;
		}

		$source_keys = array_keys( get_post_custom( (int) $from ) );
		$target_keys = array_keys( get_post_custom( (int) $to ) );
		$all_keys    = array_unique( array_merge( $source_keys, $target_keys, (array) $keys ) );

		$protected = self::protected_meta_keys();

		// Never copy TranslateSense's own operational state to another post.
		$all_keys = array_filter(
			$all_keys,
			static function ( $key ) use ( $protected ) {
				return is_string( $key )
					&& ! in_array( $key, $protected, true )
					&& 0 !== strpos( $key, '_translatesense_' );
			}
		);

		return array_values( $all_keys );
	}

	/**
	 * Preserve ACF repeater/flexible-content structural values when Polylang's
	 * ordinary post-meta synchronization setting is disabled.
	 *
	 * The parent field stores row counts/layout names and nested metadata stores
	 * ACF field-key references. Those values must remain structural, not be
	 * translated or omitted, otherwise ACF cannot resolve the translated data.
	 *
	 * @param int $source_post_id Source post ID.
	 * @param int $target_post_id Target post ID.
	 * @return void
	 */
	private static function sync_acf_structural_fields( int $source_post_id, int $target_post_id ): void {
		if ( ! function_exists( 'acf_get_field' ) ) {
			return;
		}

		$source_meta = get_post_meta( $source_post_id );
		if ( ! is_array( $source_meta ) ) {
			return;
		}

		foreach ( array_keys( $source_meta ) as $meta_key ) {
			if ( ! is_string( $meta_key ) || '' === $meta_key || '_' === $meta_key[0] ) {
				continue;
			}

			$field_key = get_post_meta( $source_post_id, '_' . $meta_key, true );
			$field     = ( is_string( $field_key ) && 0 === strpos( $field_key, 'field_' ) )
				? acf_get_field( $field_key )
				: acf_get_field( $meta_key );

			if ( ! is_array( $field ) || empty( $field['type'] ) || ! in_array( $field['type'], array( 'flexible_content', 'repeater' ), true ) ) {
				continue;
			}

			if ( isset( $source_meta[ $meta_key ][0] ) ) {
				update_post_meta(
					$target_post_id,
					sanitize_text_field( $meta_key ),
					maybe_unserialize( $source_meta[ $meta_key ][0] )
				);
			}

			if ( is_string( $field_key ) && 0 === strpos( $field_key, 'field_' ) ) {
				update_post_meta( $target_post_id, '_' . sanitize_text_field( $meta_key ), $field_key );
			}

			$nested_prefix = '_' . $meta_key . '_';
			foreach ( $source_meta as $nested_key => $values ) {
				if (
					is_string( $nested_key )
					&& 0 === strpos( $nested_key, $nested_prefix )
					&& isset( $values[0] )
					&& is_string( $values[0] )
					&& 0 === strpos( $values[0], 'field_' )
				) {
					update_post_meta( $target_post_id, sanitize_text_field( $nested_key ), $values[0] );
				}
			}
		}
	}

	/**
	 * Translate media metadata values through Polylang's media model.
	 *
	 * @param mixed  $value Metadata value.
	 * @param string $key   Metadata key.
	 * @param string $lang  Target language slug.
	 * @return mixed
	 */
	public static function translate_post_meta( $value, $key, $lang ) {
		if ( '_thumbnail_id' !== $key || ! is_numeric( $value ) ) {
			return $value;
		}

		$translated_id = self::resolve_media_translation( absint( $value ), (string) $lang );
		return $translated_id > 0 ? $translated_id : $value;
	}

	/**
	 * Resolve an existing target-language attachment or create its translation.
	 *
	 * @param int    $attachment_id Source attachment ID.
	 * @param string $target_lang   Target language slug.
	 * @return int Attachment ID, falling back to source ID when unavailable.
	 */
	private static function resolve_media_translation( int $attachment_id, string $target_lang ): int {
		if ( $attachment_id <= 0 || 'attachment' !== get_post_type( $attachment_id ) ) {
			return 0;
		}

		$polylang = self::get_polylang_instance();
		if ( ! is_object( $polylang ) || ! isset( $polylang->model->post ) || ! is_object( $polylang->model->post ) ) {
			return $attachment_id;
		}

		// Respect Polylang's Media Support setting. When disabled, media IDs
		// remain shared rather than creating language-specific attachments.
		if ( ! isset( $polylang->options ) || ! is_array( $polylang->options ) || empty( $polylang->options['media_support'] ) ) {
			return $attachment_id;
		}

		$model = $polylang->model->post;
		if ( ! is_callable( array( $model, 'get' ) ) ) {
			return $attachment_id;
		}

		$translated_id = (int) $model->get( $attachment_id, $target_lang );

		if ( $translated_id <= 0 && is_callable( array( $model, 'create_media_translation' ) ) ) {
			$created       = $model->create_media_translation( $attachment_id, $target_lang );
			$translated_id = is_numeric( $created ) ? (int) $created : 0;
		}

		if ( $translated_id > 0 && $translated_id !== $attachment_id ) {
			self::$pending_media_attachments[] = $translated_id;
		}

		return $translated_id > 0 ? $translated_id : $attachment_id;
	}

	/**
	 * Reset attachment tracking at the start of a new post translation.
	 *
	 * @return void
	 */
	public static function reset_media_tracking(): void {
		self::$pending_media_attachments = array();
	}

	/**
	 * Attach translated media used by a target post when the attachment has no
	 * parent yet. A narrowly scoped database update avoids firing another
	 * save_post/Polylang synchronization cycle for the attachment itself.
	 *
	 * @param int $target_post_id Target translated post ID.
	 * @return void
	 */
	public static function attach_translated_media_to_post( int $target_post_id ): void {
		global $wpdb;

		$target_post_id = absint( $target_post_id );
		if ( $target_post_id <= 0 || empty( self::$pending_media_attachments ) ) {
			return;
		}

		$attachment_ids = array_unique( array_filter( array_map( 'absint', self::$pending_media_attachments ) ) );

		foreach ( $attachment_ids as $attachment_id ) {
			if ( 'attachment' !== get_post_type( $attachment_id ) || wp_get_post_parent_id( $attachment_id ) ) {
				continue;
			}

			// The IDs and post type are validated above; wpdb->update prepares
			// each value and condition. Only orphaned attachment parents change.
			$updated = $wpdb->update( // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery
				$wpdb->posts,
				array( 'post_parent' => $target_post_id ),
				array(
					'ID'          => $attachment_id,
					'post_type'   => 'attachment',
					'post_parent' => 0,
				),
				array( '%d' ),
				array( '%d', '%s', '%d' )
			);

			if ( false !== $updated && $updated > 0 ) {
				clean_attachment_cache( $attachment_id );
			}
		}

		self::$pending_media_attachments = array();
	}

	/**
	 * Resolve or create a translated taxonomy term when Polylang requests one.
	 *
	 * Hierarchical parents are translated first. Existing translations are
	 * reused, and WP_Error from term insertion is handled without breaking
	 * the entire post translation.
	 *
	 * @param int    $translated_term_id Existing translated term ID, if any.
	 * @param int    $source_term_id     Source term ID.
	 * @param string $target_lang        Target language slug.
	 * @return int
	 */
	public static function maybe_translate_term( $translated_term_id, $source_term_id, $target_lang ): int {
		$translated_term_id = absint( $translated_term_id );
		$source_term_id     = absint( $source_term_id );

		if ( $translated_term_id > 0 || $source_term_id <= 0 ) {
			return $translated_term_id;
		}

		$polylang = self::get_polylang_instance();
		if (
			! is_object( $polylang )
			|| ! isset( $polylang->model->term )
			|| ! is_object( $polylang->model->term )
		) {
			return 0;
		}

		$term_model = $polylang->model->term;
		if (
			! is_callable( array( $term_model, 'get_language' ) )
			|| ! is_callable( array( $term_model, 'get_translation' ) )
			|| ! is_callable( array( $term_model, 'set_language' ) )
			|| ! is_callable( array( $term_model, 'get_translations' ) )
			|| ! is_callable( array( $term_model, 'save_translations' ) )
		) {
			return 0;
		}

		$term = get_term( $source_term_id );
		if ( ! $term instanceof WP_Term ) {
			return 0;
		}

		$source_language = $term_model->get_language( $source_term_id );
		if ( ! $source_language || $source_language->slug === $target_lang ) {
			// No translated term is required. Let Polylang's caller retain its
			// normal fallback behavior for unassigned or already-target terms.
			return 0;
		}

		$existing_id = (int) $term_model->get_translation( $source_term_id, $target_lang );
		if ( $existing_id > 0 ) {
			return $existing_id;
		}

		$parent_id = 0;
		if ( ! empty( $term->parent ) ) {
			$parent_id = (int) $term_model->get_translation( (int) $term->parent, $target_lang );

			if ( $parent_id <= 0 ) {
				$parent_id = self::maybe_translate_term( 0, (int) $term->parent, $target_lang );
			}
		}

		$force_lang = isset( $polylang->options['force_lang'] ) && $polylang->options['force_lang'];
		$term_slug  = $force_lang
			? $term->slug . '___' . $target_lang
			: sanitize_title( $term->name ) . '-' . $target_lang;

		$term_args = array(
			'description' => wp_slash( $term->description ),
			'parent'      => $parent_id,
			'slug'        => $term_slug,
		);

		$inserted = wp_insert_term( wp_slash( $term->name ), $term->taxonomy, $term_args );

		// Another request may have created the term between lookup and insert.
		if ( is_wp_error( $inserted ) ) {
			if ( 'term_exists' === $inserted->get_error_code() ) {
				$data = $inserted->get_error_data();
				if ( is_array( $data ) && isset( $data['term_id'] ) ) {
					$existing_id = absint( $data['term_id'] );
				} elseif ( is_numeric( $data ) ) {
					$existing_id = absint( $data );
				}

				if ( $existing_id > 0 ) {
					$existing_language = $term_model->get_language( $existing_id );
					if ( ! $existing_language ) {
						$term_model->set_language( $existing_id, $target_lang );
						$existing_language = $term_model->get_language( $existing_id );
					}

					if ( $existing_language && $existing_language->slug === $target_lang ) {
						$translations                 = (array) $term_model->get_translations( $source_term_id );
						$translations[ $target_lang ] = $existing_id;
						$term_model->save_translations( $source_term_id, $translations );
						return $existing_id;
					}
				}
			}
			return 0;
		}

		$new_term_id = isset( $inserted['term_id'] ) ? absint( $inserted['term_id'] ) : 0;
		if ( $new_term_id <= 0 ) {
			return 0;
		}

		$term_model->set_language( $new_term_id, $target_lang );
		$translations                 = (array) $term_model->get_translations( $source_term_id );
		$translations[ $target_lang ] = $new_term_id;
		$term_model->save_translations( $source_term_id, $translations );

		/**
		 * Fires after TranslateSense creates a missing translated term.
		 *
		 * Polylang uses this action to notify integrations of automatic term
		 * duplication. The arguments follow Polylang's established contract.
		 *
		 * @param int    $source_term_id Source term ID.
		 * @param int    $new_term_id    Newly created translated term ID.
		 * @param string $target_lang    Target language slug.
		 */
		// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- Polylang integration hook.
		do_action( 'pll_duplicate_term', $source_term_id, $new_term_id, $target_lang );

		return $new_term_id;
	}

	/**
	 * Translate media references in translated content without translating text.
	 *
	 * Handles Gutenberg attachment attributes, classic WordPress image classes,
	 * and gallery/playlist shortcode ID lists. Unknown IDs and non-media values
	 * are left unchanged.
	 *
	 * @param string $content    Already translated content.
	 * @param string $target_lang Target language slug.
	 * @param string $builder    Builder slug.
	 * @return string
	 */
	public static function translate_content_media_references( string $content, string $target_lang, string $builder = '', string $source_lang = '' ): string {
		if ( '' === $content ) {
			return $content;
		}

		$translator = new Internal_Link_Translator();
		$batch      = array( 'content' => $content );
		$translated = $translator->translate_batch( $batch, $target_lang );

		return is_string( $translated['content'] ?? null ) ? $translated['content'] : $content;
	}

	/**
	 * Update attachment references inside standard WordPress image tags.
	 *
	 * The method only acts on <img> elements carrying a WordPress attachment
	 * class or data-id attribute. It does not rewrite arbitrary image URLs.
	 *
	 * @param string $content    HTML content.
	 * @param string $target_lang Target language.
	 * @return string
	 */
	private static function translate_html_image_references( string $content, string $target_lang ): string {
		$translated_image_ids = array();

		$content = preg_replace_callback(
			'/<img\b[^>]*>/i',
			static function ( $matches ) use ( $target_lang, &$translated_image_ids ) {
				$tag       = $matches[0];
				$source_id = 0;

				if ( preg_match( '/\bwp-image-(\d+)\b/', $tag, $class_match ) ) {
					$source_id = absint( $class_match[1] );
				} elseif ( preg_match( '/\bdata-id\s*=\s*(["\'])(\d+)\1/i', $tag, $data_match ) ) {
					$source_id = absint( $data_match[2] );
				}

				if ( $source_id <= 0 ) {
					$translated_image_ids[] = 0;
					return $tag;
				}

				$translated_id = self::resolve_media_translation( $source_id, $target_lang );
				if ( $translated_id <= 0 || $translated_id === $source_id ) {
					$translated_image_ids[] = 0;
					return $tag;
				}

				$translated_image_ids[] = $translated_id;
				$tag                    = preg_replace( '/\bwp-image-' . preg_quote( (string) $source_id, '/' ) . '\b/', 'wp-image-' . $translated_id, $tag );

				// Update data-id and builder-specific data-link attachment IDs.
				$tag = preg_replace_callback(
					'/\bdata-id\s*=\s*(["\'])(\d+)\1/i',
					static function ( $attribute ) use ( $source_id, $translated_id ) {
						return absint( $attribute[2] ) === $source_id
							? 'data-id=' . $attribute[1] . $translated_id . $attribute[1]
							: $attribute[0];
					},
					$tag
				);

				$tag = preg_replace_callback(
					'/\bdata-link\s*=\s*(["\'])(.*?)\1/i',
					static function ( $attribute ) use ( $source_id, $translated_id ) {
						return preg_match( '/attachment_id=' . preg_quote( (string) $source_id, '/' ) . '\b/', $attribute[2] )
							? 'data-link=' . $attribute[1] . str_replace( 'attachment_id=' . $source_id, 'attachment_id=' . $translated_id, $attribute[2] ) . $attribute[1]
							: $attribute[0];
					},
					$tag
				);

				// Use the translated attachment's URL and alt text where available.
				$image = wp_get_attachment_image_src( $translated_id, 'full' );
				if ( is_array( $image ) && ! empty( $image[0] ) ) {
					$tag = preg_replace_callback(
						'/\bsrc\s*=\s*(["\'])(.*?)\1/i',
						static function ( $attribute ) use ( $image ) {
							return 'src=' . $attribute[1] . esc_url( $image[0] ) . $attribute[1];
						},
						$tag
					);
				}

				$srcset = wp_get_attachment_image_srcset( $translated_id, 'full' );
				if ( $srcset ) {
					$tag = preg_replace_callback(
						'/\bsrcset\s*=\s*(["\'])(.*?)\1/i',
						static function ( $attribute ) use ( $srcset ) {
							return 'srcset=' . $attribute[1] . esc_attr( $srcset ) . $attribute[1];
						},
						$tag
					);
				}

				$translated_alt = get_post_meta( $translated_id, '_wp_attachment_image_alt', true );
				if ( is_string( $translated_alt ) && '' !== $translated_alt ) {
					$tag = preg_replace_callback(
						'/\balt\s*=\s*(["\'])(.*?)\1/i',
						static function ( $attribute ) use ( $translated_alt ) {
							return 'alt=' . $attribute[1] . esc_attr( $translated_alt ) . $attribute[1];
						},
						$tag
					);
				}

				return $tag;
			},
			$content
		);

		// Replace figcaption text only when the translated attachment provides
		// a translated post excerpt. Existing captions remain untouched otherwise.
		$caption_index = 0;
		$content       = preg_replace_callback(
			'@(?<before><figcaption\b[^>]*>)(?<caption>.*?)(?<after></figcaption>)@is',
			static function ( $matches ) use ( $translated_image_ids, &$caption_index ) {
				$attachment_id = isset( $translated_image_ids[ $caption_index ] ) ? absint( $translated_image_ids[ $caption_index ] ) : 0;
				$caption_index++;

				if ( $attachment_id > 0 ) {
					$attachment = get_post( $attachment_id );
					if ( $attachment instanceof WP_Post && '' !== $attachment->post_excerpt ) {
						return $matches['before'] . wp_kses_post( $attachment->post_excerpt ) . $matches['after'];
					}
				}

				return $matches[0];
			},
			$content
		);

		return $content;
	}

	/**
	 * Recursively translate known Gutenberg media block attributes.
	 *
	 * @param array  $blocks      Parsed block tree.
	 * @param string $target_lang Target language.
	 * @return array
	 */
	private static function translate_block_media( array $blocks, string $target_lang, string $source_lang = '' ): array {
		$media_blocks = array(
			'core/image',
			'core/cover',
			'core/video',
			'core/audio',
			'core/file',
			'core/media-text',
		);

		foreach ( $blocks as &$block ) {
			if ( ! is_array( $block ) ) {
				continue;
			}

			$name = isset( $block['blockName'] ) ? (string) $block['blockName'] : '';

			// Reusable blocks are translated posts (`wp_block`). Replace the
			// source reference only when a target-language translation exists.
			if ( 'core/block' === $name && isset( $block['attrs']['ref'] ) ) {
				$polylang = self::get_polylang_instance();
				if (
					is_object( $polylang )
					&& isset( $polylang->model->post )
					&& is_object( $polylang->model->post )
					&& is_callable( array( $polylang->model->post, 'get' ) )
					&& ( ! is_callable( array( $polylang->model, 'is_translated_post_type' ) ) || $polylang->model->is_translated_post_type( 'wp_block' ) )
				) {
					$translated_ref = (int) $polylang->model->post->get( absint( $block['attrs']['ref'] ), $target_lang );
					if ( $translated_ref > 0 ) {
						$block['attrs']['ref'] = $translated_ref;
					}
				}
			}

			// The latest-posts block stores category objects rather than simple
			// term IDs. Keep only categories with an existing target translation.
			if ( 'core/latest-posts' === $name && isset( $block['attrs']['categories'] ) && is_array( $block['attrs']['categories'] ) ) {
				$polylang              = self::get_polylang_instance();
				$translated_categories = array();

				if ( is_object( $polylang ) && isset( $polylang->model->term ) && is_object( $polylang->model->term ) && is_callable( array( $polylang->model->term, 'get' ) ) ) {
					foreach ( $block['attrs']['categories'] as $category ) {
						$source_term_id     = is_array( $category ) && isset( $category['id'] ) ? absint( $category['id'] ) : 0;
						$translated_term_id = $source_term_id > 0 ? (int) $polylang->model->term->get( $source_term_id, $target_lang ) : 0;
						if ( $translated_term_id > 0 ) {
							$translated_term = get_term( $translated_term_id );
							if ( $translated_term instanceof WP_Term ) {
								$translated_categories[] = array(
									'id'    => $translated_term_id,
									'value' => $translated_term->name,
								);
							}
						}
					}
				}

				if ( $translated_categories ) {
					$block['attrs']['categories'] = $translated_categories;
				} else {
					unset( $block['attrs']['categories'] );
				}
			}

			$media_attribute = 'core/media-text' === $name ? 'mediaId' : 'id';
			if ( in_array( $name, $media_blocks, true ) && isset( $block['attrs'][ $media_attribute ] ) ) {
				$source_media_id = absint( $block['attrs'][ $media_attribute ] );
				$translated_id   = self::resolve_media_translation( $source_media_id, $target_lang );
				if ( $translated_id > 0 ) {
					$block['attrs'][ $media_attribute ] = $translated_id;
					$translated_url                     = wp_get_attachment_url( $translated_id );
					if ( $translated_url ) {
						foreach ( array( 'url', 'href', 'mediaUrl' ) as $url_key ) {
							if ( isset( $block['attrs'][ $url_key ] ) ) {
								$block['attrs'][ $url_key ] = $translated_url;
							}
						}
					}
					if ( 'core/file' === $name && ! empty( $block['innerHTML'] ) ) {
						$source_media = get_post( $source_media_id );
						$target_media = get_post( $translated_id );
						if ( $source_media instanceof WP_Post && $target_media instanceof WP_Post && $source_media->post_title === wp_strip_all_tags( $block['innerHTML'] ) ) {
							$block['innerHTML'] = str_replace( $source_media->post_title, $target_media->post_title, $block['innerHTML'] );
							if ( ! empty( $block['innerContent'][0] ) ) {
								$block['innerContent'][0] = str_replace( $source_media->post_title, $target_media->post_title, $block['innerContent'][0] );
							}
						}
					}
				}
			}

			if ( 'core/gallery' === $name && ! empty( $block['attrs']['ids'] ) && is_array( $block['attrs']['ids'] ) ) {
				foreach ( $block['attrs']['ids'] as &$media_id ) {
					$translated_id = self::resolve_media_translation( absint( $media_id ), $target_lang );
					if ( $translated_id > 0 ) {
						$media_id = $translated_id;
					}
				}
				unset( $media_id );
			}

			if ( ! empty( $block['innerBlocks'] ) && is_array( $block['innerBlocks'] ) ) {
				$block['innerBlocks'] = self::translate_block_media( $block['innerBlocks'], $target_lang, $source_lang );
			}
		}
		unset( $block );

		/**
		 * Filters parsed blocks after core media and Polylang references have
		 * been translated. Other Polylang integrations can adjust custom blocks.
		 *
		 * @param array[] $blocks      Parsed blocks.
		 * @param string  $target_lang Target language slug.
		 * @param string  $source_lang Source language slug.
		 */
		// phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- Polylang integration filter.
		return apply_filters( 'pll_translate_blocks', $blocks, $target_lang, $source_lang );
	}

	/**
	 * Translate media references in an Elementor settings/data structure.
	 *
	 * @param mixed  $data        Elementor data (array or JSON string).
	 * @param string $target_lang Target language.
	 * @return mixed
	 */
	public static function translate_elementor_media_data( $data, string $target_lang ) {
		$translator = new Internal_Link_Translator();
		$batch      = array( 'elementor' => $data );
		$translated = $translator->translate_batch( $batch, $target_lang );

		return $translated['elementor'] ?? $data;
	}

	/**
	 * Translate common Elementor media ID fields in its JSON document.
	 *
	 * Only ID fields nested in media-related settings are changed. Elementor
	 * element IDs, section IDs, form IDs and unrelated numeric values remain
	 * untouched.
	 *
	 * @param string $content    Elementor JSON.
	 * @param string $target_lang Target language.
	 * @return string
	 */
	private static function translate_elementor_media_json( string $content, string $target_lang ): string {
		$data = json_decode( $content, true );
		if ( ! is_array( $data ) || json_last_error() !== JSON_ERROR_NONE ) {
			return $content;
		}

		$data = self::walk_elementor_media_data( $data, $target_lang, '' );
		$json = wp_json_encode( $data );

		return is_string( $json ) ? $json : $content;
	}

	/**
	 * Recursively inspect Elementor settings for media objects.
	 *
	 * @param mixed  $value      Current value.
	 * @param string $target_lang Target language.
	 * @param string $parent_key Parent array key.
	 * @return mixed
	 */
	private static function walk_elementor_media_data( $value, string $target_lang, string $parent_key, bool $in_media_context = false ) {
		if ( ! is_array( $value ) ) {
			return $value;
		}

		$media_context = $in_media_context || (bool) preg_match( '/image|media|gallery|video|audio|background|poster|attachment/i', $parent_key );

		foreach ( $value as $key => &$item ) {
			$key_string = (string) $key;

			if ( $media_context && in_array( $key_string, array( 'id', 'image_id', 'attachment_id' ), true ) && is_numeric( $item ) ) {
				$translated_id = self::resolve_media_translation( absint( $item ), $target_lang );
				if ( $translated_id > 0 ) {
					$item           = $translated_id;
					$translated_url = wp_get_attachment_url( $translated_id );
					if ( $translated_url && isset( $value['url'] ) ) {
						$value['url'] = $translated_url;
					}
				}
				continue;
			}

			$item = self::walk_elementor_media_data( $item, $target_lang, $key_string, $media_context );
		}
		unset( $item );

		return $value;
	}

	/**
	 * Check whether a Polylang copy filter is running for our exact pair.
	 *
	 * @param int $from Source post ID.
	 * @param int $to   Target post ID.
	 * @return bool
	 */
	private static function is_active_pair( $from, $to ): bool {
		return ! empty( self::$context )
			&& absint( $from ) === (int) self::$context['source_post_id']
			&& absint( $to ) === (int) self::$context['target_post_id'];
	}
